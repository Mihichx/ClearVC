<?php

namespace Core;

use PDO;

/**
 * Главный контейнер приложения (App).
 * Реализует паттерн "Реестр" (Registry) и "Сервис-локатор" (Service Locator).
 * Служит единой глобальной точкой доступа к ключевым системным объектам (база данных, 
 * запросы, конфигурация), избавляя от необходимости передавать их через аргументы методов.
 */
class App
{
    /**
     * Глобальный объект подключения к базе данных PDO.
     * Инициализируется один раз при старте приложения в index.php.
     * 
     * @var PDO|null
     */
    private static ?PDO $db = null;

    /**
     * Регистрирует (сохраняет) активное подключение к базе данных в контейнере.
     * Метод вызывается один раз на этапе инициализации приложения в файле public/index.php.
     * 
     * @param PDO $db Сконфигурированный объект подключения к БД PDO
     * @return void
     */
    public static function setDb(PDO $db): void
    {
        self::$db = $db;
    }

    /**
     * Возвращает экземпляр подключения к базе данных из любой точки проекта.
     * Перед отдачей проверяет, было ли соединение инициализировано, предотвращая 
     * работу с невалидным состоянием.
     * 
     * @throws \RuntimeException Если метод вызван до инициализации базы данных через setDb()
     * @return PDO Активный объект подключения к базе данных
     */
    public static function db(): PDO
    {
        if (self::$db === null) {
            throw new \RuntimeException(
                "Критическая ошибка ядра: База данных не инициализирована в глобальном контейнере App. " .
                    "Убедитесь, что метод App::setDb(\$db) вызывается в файле public/index.php до запуска роутера."
            );
        }
        return self::$db;
    }
}
